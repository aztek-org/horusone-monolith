export const useChecklist = () => {
  const items = useState<ChecklistItem[]>('checklist', () => [...defaultChecklist])
  const autoGenEnabled = useState('checklistAutoGen', () => true)

  const categories = computed(() => {
    const cats = new Set(items.value.map(item => item.category))
    return Array.from(cats)
  })

  const itemsByCategory = computed(() => {
    const grouped: Record<string, ChecklistItem[]> = {}
    categories.value.forEach((cat) => {
      grouped[cat] = items.value.filter(item => item.category === cat)
    })
    return grouped
  })

  const completedCount = computed(() =>
    items.value.filter(item => item.status === 'completed').length,
  )

  const totalCount = computed(() => items.value.length)

  const progressPercentage = computed(() =>
    totalCount.value > 0 ? (completedCount.value / totalCount.value) * 100 : 0,
  )

  function addItem(item: Omit<ChecklistItem, 'id'>) {
    const id = `cl-${Date.now()}`
    items.value.push({ ...item, id })
    return id
  }

  function updateItem(id: string, updates: Partial<Omit<ChecklistItem, 'id'>>) {
    const index = items.value.findIndex(item => item.id === id)
    const existing = items.value[index]
    if (existing) {
      Object.assign(existing, updates)
    }
  }

  function completeItem(id: string) {
    updateItem(id, { status: 'completed' })
  }

  function removeItem(id: string) {
    const index = items.value.findIndex(item => item.id === id)
    if (index !== -1) {
      items.value.splice(index, 1)
    }
  }

  function toggleAutoGen() {
    autoGenEnabled.value = !autoGenEnabled.value
  }

  function resetChecklist() {
    items.value = [...defaultChecklist]
  }

  return {
    items: readonly(items),
    categories,
    itemsByCategory,
    completedCount,
    totalCount,
    progressPercentage,
    autoGenEnabled: readonly(autoGenEnabled),
    addItem,
    updateItem,
    completeItem,
    removeItem,
    toggleAutoGen,
    resetChecklist,
  }
}
